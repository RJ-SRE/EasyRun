// Reproducible offline content build. Sources and normalization are checked in.
import { Buffer } from "node:buffer";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { WORDS as curated } from "../prototypes/runlab/data/cet4-curated.js";
const root = new URL("../", import.meta.url);
const source = JSON.parse(
  await readFile(
    new URL("prototypes/runlab/data/cet-source.json", root),
    "utf8",
  ),
);
const senseOverrides = JSON.parse(
  await readFile(
    new URL("prototypes/runlab/data/cet-meaning-overrides.json", root),
    "utf8",
  ),
);
const overrides = new Map(curated.map((w) => [w.word, w]));
const strip = (s) =>
  s.replace(/\[[^\]]*\]|\([^)]*\)|（[^）]*）/g, "").replace(/\s+/g, "");
const normalizePos = (pos) =>
  (({
    a: "adj",
    ad: "adv",
    vt: "v",
    vi: "v",
    vti: "v",
    art: "art",
    num: "num",
    aux: "v",
    int: "int",
    interj: "int",
  })[pos] || pos) + ".";
const words = source.entries.map((entry) => {
  const old = overrides.get(entry.word);
  const sense = senseOverrides[entry.word];
  const lines = entry.translation
    .replaceAll("\\r", "")
    .replaceAll("\\n", "\n")
    .split("\n");
  const general =
    lines.find((l) => /^(?:[a-z]+\.)/.test(l) && /[\u4e00-\u9fff]/.test(l)) ||
    lines.find((l) => /[\u4e00-\u9fff]/.test(l));
  if (!general) throw new Error(`Missing translation: ${entry.word}`);
  const posMatch = general.match(/^([a-z]+)\./);
  const pos = normalizePos(posMatch?.[1] || "词");
  const senses = strip(general.replace(/^[a-z]+\./, ""))
    .split(/[,，;；]/)
    .filter((v) => /[\u4e00-\u9fff]/.test(v));
  const meaning =
    senses
      .filter((v) => v.length <= 22)
      .slice(0, 2)
      .join("；") || senses[0];
  if (!meaning || meaning.length > 48)
    throw new Error(`Invalid meaning: ${entry.word}: ${meaning}`);
  return {
    id: entry.word,
    word: entry.word,
    accepted: entry.accepted,
    pos: sense?.pos || old?.pos || pos,
    meaning: sense?.meaning || old?.meaning || meaning,
    context: old?.context || `${entry.word} · ${sense?.pos || pos} 常用义`,
    distractors: old?.distractors || [],
    tier:
      old?.tier ||
      (entry.word.length <= 6 ? 1 : entry.word.length >= 10 ? 3 : 2),
    levels: entry.levels,
    source: "cet2016-ecdict-ab22ad3",
    spellable: /^[a-z]+$/.test(entry.word),
    allMeanings: strip(entry.translation + (sense?.meaning || "")),
    original: entry.original,
  };
});
// Prefer same-part-of-speech distractors, reject any overlap with ANY documented
// sense (including other POS); never choose another spelling of the target.
for (const w of words) {
  if (w.distractors.length) continue;
  const hash = parseInt(
    createHash("sha256").update(w.id).digest("hex").slice(0, 8),
    16,
  );
  const primary = w.pos.replace(/vt|vi/, "v");
  const candidates = words.filter(
    (other) =>
      other.id !== w.id &&
      !w.accepted.includes(other.word) &&
      other.pos.replace(/vt|vi/, "v") === primary &&
      other.meaning.length <= 18,
  );
  const acceptable = (other) => {
    const target = w.allMeanings,
      otherSenses = other.meaning.split(/[；，,]/);
    return (
      otherSenses.every(
        (s) =>
          !target.includes(s) &&
          !w.meaning.includes(s) &&
          !other.allMeanings.includes(w.meaning),
      ) &&
      !w.meaning.split(/[；，,]/).some((s) => other.allMeanings.includes(s)) &&
      ![...other.meaning]
        .filter((c) => /[\u4e00-\u9fff]/.test(c))
        .some((c) => w.meaning.includes(c))
    );
  };
  for (const group of [candidates, words]) {
    for (let n = 0; n < group.length && w.distractors.length < 2; n++) {
      const other = group[(hash + n * 37) % group.length];
      if (
        acceptable(other) &&
        !w.distractors.includes(other.meaning) &&
        !w.distractors.some((v) =>
          v.split("；").some((x) => other.meaning.includes(x)),
        )
      )
        w.distractors.push(other.meaning);
    }
  }
  if (w.distractors.length !== 2) throw new Error(`No unique options: ${w.id}`);
}
for (const w of words) {
  delete w.allMeanings;
  delete w.original;
}
const coverage = {
  ...source.coverage,
  total: words.length,
  cet4: words.filter((w) => w.levels.includes("cet4")).length,
  cet6: words.filter((w) => w.levels.includes("cet6")).length,
  source: "CET 2016 词表 + ECDICT 固定版本",
  version: "cet46-2026-10-26.1",
};
const output = `// Generated by scripts/build-wordbank.mjs; sources: docs/WORD_BANK.md.\nexport const CONTENT_VERSION = ${JSON.stringify(coverage.version)};\nexport const COVERAGE = ${JSON.stringify(coverage)};\nexport const WORDS = ${JSON.stringify(words)};\n`;
await writeFile(
  new URL("prototypes/runlab/public/cet4-words.js", root),
  output,
);
await writeFile(
  new URL("prototypes/runlab/data/cet-coverage.json", root),
  JSON.stringify(coverage, null, 2) + "\n",
);
console.log(
  JSON.stringify({ ...coverage, bytes: Buffer.byteLength(output) }, null, 2),
);
